// Copies the transition catalogue (src/argon/transitions.ts) to the app (frontend/lib/transitions.ts), so the picker
// previews exactly what the film engine draws. Run after editing the catalogue: node transitions-sync.mjs
import fs from "node:fs"; import path from "node:path"; import { fileURLToPath } from "node:url";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(HERE, "src/argon/transitions.ts"), "utf8");
const out = path.join(HERE, "..", "frontend", "lib", "transitions.ts");
fs.writeFileSync(out, `// GENERATED by video/transitions-sync.mjs from video/src/argon/transitions.ts: edit that file, not this one.\n${src}`);
console.log("wrote", path.relative(process.cwd(), out));
